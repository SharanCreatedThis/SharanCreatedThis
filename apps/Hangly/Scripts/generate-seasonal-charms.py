#!/usr/bin/env python3
"""Draws the seasonal charms into Assets/Charms as SVG.

The eleven collection charms were illustrated by hand. These were constructed —
which is a different way of drawing, and the reason they are generated by a script
rather than exported from an editor: a snowflake's six-fold symmetry and a coin's
concentric rims are arithmetic, and arithmetic is better written down than clicked.

Everything here shares one style kit so the packs sit together and sit beside the
hand-drawn collection: light from the upper left, a dark contour under every shape,
a gradient fill over it, a specular highlight on top, and the collection's gold on
the cord and the beads. Re-run after editing, then Scripts/sync-charm-assets.sh.
"""

import pathlib
