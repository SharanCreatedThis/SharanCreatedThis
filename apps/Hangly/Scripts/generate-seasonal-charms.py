# ---------------------------------------------------------------- Christmas

def snowflake():
    contour, radius = "#10456a", 40.0
    arms = []
    for index in range(6):
        angle = math.radians(index * 60)
        ux, uy = math.sin(angle), -math.cos(angle)
        arms.append(f"M{CX:.2f},{BODY_Y:.2f}L{CX + ux * radius:.2f},{BODY_Y + uy * radius:.2f}")
        for station, span in ((0.40, 0.34), (0.68, 0.26)):
            bx, by = CX + ux * radius * station, BODY_Y + uy * radius * station
            for side in (-1, 1):
                branch = angle + side * math.radians(52)
                arms.append(
                    f"M{bx:.2f},{by:.2f}"
                    f"L{bx + math.sin(branch) * radius * span:.2f},"
                    f"{by - math.cos(branch) * radius * span:.2f}"
                )
    path = "".join(arms)
    defs = three("ice", ("#ffffff", "#a9dcf5", "#1f5f88")) \
        + three("iceBead", ("#ffffff", "#9fd6f2", "#215f86"), radial=True) \
        + three("core", ("#ffffff", "#bfe6fa", "#3e86b0"), radial=True)
    return header(defs) + hanger("url(#iceBead)", contour) + f"""  <g fill="none" stroke-linecap="round">
    <path d="{path}" stroke="{contour}" stroke-width="9.4"/>
    <path d="{path}" stroke="url(#ice)" stroke-width="6.6"/>
    <path d="{path}" stroke="#ffffff" stroke-width="1.9" opacity="0.55" transform="translate(-1.05,-1.05)"/>
  </g>
  <circle cx="{CX:g}" cy="{BODY_Y:g}" r="13.4" fill="{contour}"/>
  <circle cx="{CX:g}" cy="{BODY_Y:g}" r="11.6" fill="url(#gold)"/>
  <circle cx="{CX:g}" cy="{BODY_Y:g}" r="8.2" fill="{contour}"/>
  <circle cx="{CX:g}" cy="{BODY_Y:g}" r="7.1" fill="url(#core)"/>
  {spark(CX - 2.5, BODY_Y - 2.7, 3, 2.1, 0.9)}
</svg>
"""


