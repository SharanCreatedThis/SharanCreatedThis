/**
 * Builds the changelog page's data from the Sparkle feeds.
 *
 * The release notes already exist, in the appcasts, where the updater reads
 * them. Retyping them into a page is how a changelog ends up disagreeing with
 * what the updater shows — so the page is generated from the same file, and
 * a release that is not in a feed cannot appear on the page at all.
 *
 * The feeds are read, never written. Vision's appcast in particular is signed
 * infrastructure that installed copies depend on.
 *
 * Windows has no Sparkle feed — it updates through Velopack, whose feed lives
 * inside the release — so its version is taken from the redirects generated
 * just before this script runs, and the page links out to the GitHub release
 * for the notes rather than inventing them.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

const pick = (xml, tag) => (xml.match(new RegExp(`<${tag}[^>]*>([\\s\\S]*?)</${tag}>`)) || [, ""])[1].trim();
const attr = (xml, name) => (xml.match(new RegExp(`${name}="([^"]*)"`)) || [, ""])[1];

/** CDATA HTML to plain paragraphs and bullets. The page renders text, not HTML. */
function notes(html) {
  const body = html.replace(/^<!\[CDATA\[/, "").replace(/\]\]>$/, "");
  const out = [];
  for (const m of body.matchAll(/<(p|li)\b[^>]*>([\s\S]*?)<\/\1>/g)) {
    const t = m[2].replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/&lt;/g, "<")
      .replace(/&gt;/g, ">").replace(/&#39;|&rsquo;/g, "'").replace(/&quot;/g, '"')
      .replace(/\s+/g, " ").trim();
    if (t) out.push({ kind: m[1] === "li" ? "point" : "para", text: t });
  }
  return out;
}

function feed(product, path, fallbackName) {
  const xml = read(path);
  return [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)].map((m) => {
    const item = m[1];
    const enclosure = (item.match(/<enclosure[\s\S]*?\/>/) || [""])[0];
    const version =
      pick(item, "sparkle:shortVersionString") || attr(enclosure, "sparkle:shortVersionString") || pick(item, "title");
    return {
      product,
      name: fallbackName,
      platform: "macOS",
      version: version.replace(/^\D+/, "") || version,
      date: new Date(pick(item, "pubDate")).toISOString().slice(0, 10),
      minimumSystem: pick(item, "sparkle:minimumSystemVersion") || attr(enclosure, "sparkle:minimumSystemVersion"),
      bytes: Number(attr(enclosure, "length")) || 0,
      notes: notes(pick(item, "description")),
      notesUrl: pick(item, "sparkle:releaseNotesLink").trim() || "",
    };
  });
}

const releases = [
  ...feed("hangly", "public/products/hangly/appcast.xml", "Hangly"),
  ...feed("vision", "public/products/vision/appcast.xml", "Vision"),
];

/* The Windows build, from the redirects the previous script just wrote. */
const redirects = read("public/_redirects");
const win = redirects.match(/Hangly-Windows\/releases\/download\/v([\d.]+)\//);
if (win) {
  releases.push({
    product: "hangly",
    name: "Hangly",
    platform: "Windows",
    version: win[1],
    date: "",
    minimumSystem: "10.0",
    bytes: 0,
    notes: [],
    notesUrl: `https://github.com/SharanCreatedThis/Hangly-Windows/releases/tag/v${win[1]}`,
  });
}

releases.sort((a, b) => (b.date || "0").localeCompare(a.date || "0"));

writeFileSync(
  join(root, "src/data/changelog.generated.ts"),
  `// Generated by scripts/generate-changelog.mjs from the Sparkle feeds. Do not edit.\n` +
    `export type Release = {\n` +
    `  product: "hangly" | "vision";\n  name: string;\n  platform: string;\n  version: string;\n` +
    `  /** ISO date, or "" where the feed carries none. */\n  date: string;\n` +
    `  minimumSystem: string;\n  bytes: number;\n` +
    `  notes: { kind: "para" | "point"; text: string }[];\n  notesUrl: string;\n};\n\n` +
    `export const RELEASES: Release[] = ${JSON.stringify(releases, null, 2)};\n`,
  "utf8",
);
console.log(`  changelog: ${releases.length} releases from ${new Set(releases.map((r) => r.product)).size} feeds`);
