/**
 * Records when the site's content last actually changed, for sitemap lastmod.
 *
 * lastmod was the build time, which meant every page claimed to have changed
 * every time anything was deployed — a typo fix in one component moved all nine
 * dates, and a rebuild with no changes at all moved them too. Google uses
 * lastmod only where it has found it consistently accurate and ignores it
 * everywhere else, so a date that is always "now" is worse than no date: it is
 * a field being actively trained to be disbelieved.
 *
 * The date here is the last commit that touched anything the visitor sees.
 * Generated files are excluded, because they change on every build by
 * definition and would put the lie straight back in.
 *
 * This is site-level rather than per-page. Per-page would need to know which
 * components each route renders, and a page's content comes as much from shared
 * components as from its own file — a wrong per-page date is no better than a
 * wrong global one. One honest date for the site is the claim that can be
 * defended.
 *
 * Falls back to the build time when git is unavailable or the checkout is too
 * shallow to answer, which is possible on a CI runner. A fallback that is
 * merely imprecise is better than a build that fails over a hint field.
 */

import { execFileSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "src/data/content-date.generated.ts");

/** Everything a reader sees, minus anything a build writes. */
const WATCHED = ["src", "public"];
const IGNORED = [
  ":(exclude)src/data/*.generated.ts",
  ":(exclude)public/_redirects",
  ":(exclude)public/*.txt",
];

function lastContentChange() {
  try {
    const iso = execFileSync(
      "git",
      ["log", "-1", "--format=%cI", "--", ...WATCHED, ...IGNORED],
      { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    ).trim();
    // An empty answer means a shallow clone with nothing matching in it.
    return iso && !Number.isNaN(Date.parse(iso)) ? iso : null;
  } catch {
    return null;
  }
}

const date = lastContentChange();

mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `// Generated by scripts/generate-content-date.mjs — do not edit.\n` +
    `// The last commit that changed anything a visitor sees.\n\n` +
    `export const CONTENT_LAST_MODIFIED = ${JSON.stringify(date ?? new Date().toISOString())};\n` +
    `export const CONTENT_DATE_FROM_GIT = ${Boolean(date)};\n`,
);

console.log(
  date
    ? `  content date: ${date} (from git)`
    : `  content date: build time — git unavailable or checkout too shallow`,
);
