/**
 * Works out where each charm's artwork actually lives, once, at build time.
 *
 * There are two renderings of every charm. `public/charms/<name>.svg` is the
 * charm alone; `public/charms/connected/<name>.svg` is the same artwork with the
 * hanging thread drawn in, and that thread ends at the charm's own loop — a
 * different place in every file — so one cannot be derived from the other by
 * any rule. It is drawn per charm, by hand.
 *
 * Six collections shipped before their connected artwork did. The page asked
 * for `/charms/connected/<name>.svg` regardless, so thirty charms rendered as
 * broken images and thirty links 404ed, on the most visited page of the site.
 * The art was never missing — it was one directory up the whole time.
 *
 * So this resolves each name to the best file that exists, preferring the
 * connected rendering and falling back to the plain one, and writes the result
 * as a module the page imports. When the remaining connected artwork is drawn,
 * dropping the files into place is the entire change: the next build picks them
 * up and the fallback stops applying, with nothing to edit here.
 *
 * A charm with no artwork at all fails the build, because the alternative is
 * shipping a broken image and finding out from a stranger.
 */

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "src/data/charms.generated.ts");

const shipped = JSON.parse(readFileSync(join(root, "src/data/hangly/charm-library.shipped.json"), "utf8"));
// Shipped id → website file name (walterWhite is breakingBad1 on disk), read from artwork.ts as the artwork check reads it.
const artworkSource = readFileSync(join(root, "src/lib/charms/artwork.ts"), "utf8");
const aliasBody = artworkSource.slice(artworkSource.indexOf("ARTWORK_ALIAS: Record<string, string> = {"));
const alias = Object.fromEntries(
  [...aliasBody.slice(0, aliasBody.indexOf("\n};")).matchAll(/(\w+):\s*"([^"]+)"/g)].map((m) => [m[1], m[2]]),
);

/** Every charm the page can show: the whole shipped catalogue, plus any named one at a time. */
function charmNames() {
  const names = shipped.charms.map((c) => c.id);
  // The demo picks a handful directly rather than through a collection.
  const demo = readFileSync(join(root, "src/components/hangly/Demo.tsx"), "utf8");
  for (const match of demo.matchAll(/\[\s*'([A-Za-z0-9]+)'\s*,\s*'/g)) names.push(match[1]);
  // Named one at a time around the page.
  for (const file of ["Hero.tsx", "CTA.tsx", "Features.tsx"]) {
    const path = join(root, "src/components/hangly", file);
    if (!existsSync(path)) continue;
    const text = readFileSync(path, "utf8");
    for (const match of text.matchAll(/<Charm\s+name="([A-Za-z0-9]+)"/g)) names.push(match[1]);
    for (const match of text.matchAll(/\['([A-Za-z0-9]+)','[^']*'\]/g)) names.push(match[1]);
  }
  return [...new Set(names)];
}

const names = charmNames();
if (names.length === 0) throw new Error("no charms found — has the shipped catalogue changed shape?");

const current = JSON.parse(readFileSync(join(root, "src/data/hangly/charm-artwork-current.json"), "utf8"));
const resolved = {};
const fallbacks = [];
const missing = [];

for (const name of names) {
  const file = alias[name] ?? name;
  const connected = `/charms/connected/${file}.svg`;
  const plain = `/charms/${file}.svg`;
  // The app's own Library preview, for charms the website has no SVG of (scripts/import-charm-previews.mjs).
  const preview = `/charms/${name}.webp`;
  if (current[name] && existsSync(join(root, "public", current[name].path))) {
    resolved[name] = current[name].path;
  } else if (existsSync(join(root, "public", connected))) {
    resolved[name] = connected;
  } else if (existsSync(join(root, "public", plain))) {
    resolved[name] = plain;
    fallbacks.push(name);
  } else if (existsSync(join(root, "public", preview))) {
    resolved[name] = preview;
    fallbacks.push(name);
  } else {
    missing.push(name);
  }
}

if (missing.length) {
  throw new Error(
    `no artwork for ${missing.length} charm(s): ${missing.join(", ")}\n` +
      `  Expected public/charms/connected/<name>.svg, public/charms/<name>.svg or public/charms/<id>.webp`,
  );
}

// The collections strip, in the app's own order: each category with its charms' ids and names. Only what the
// strip shows, so the page does not ship every charm's description to the browser.
const collections = shipped.categories
  .map((category) => ({
    id: category.id,
    name: category.name,
    charms: shipped.charms.filter((c) => c.category === category.id).map((c) => [c.id, c.name]),
  }))
  .filter((category) => category.charms.length > 0);

mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `// Generated by scripts/generate-charm-manifest.mjs — do not edit.\n` +
    `// Each charm resolved to its best available artwork: the connected\n` +
    `// rendering where one has been drawn, the plain one otherwise, the app's preview last.\n\n` +
    `export const CHARM_ART: Record<string, string> = ${JSON.stringify(resolved, null, 2)};\n\n` +
    `// The shipped catalogue's categories, in the app's order, for the collections strip.\n` +
    `export const CHARM_COLLECTIONS: { id: string; name: string; charms: [string, string][] }[] = ${JSON.stringify(collections, null, 2)};\n`,
);

console.log(
  `  charms: ${names.length} resolved` +
    (fallbacks.length
      ? `, ${fallbacks.length} still waiting on connected artwork (${fallbacks.slice(0, 3).join(", ")}…)`
      : ""),
);
